// Assembles the Hostinger upload: single domain with dedicated app pages.
// Usage: node scripts/build.mjs   → deploy/main/ (with all app pages) and deploy/zips/main.zip
import { readFileSync, writeFileSync, rmSync, mkdirSync, cpSync, readdirSync, statSync, existsSync } from 'node:fs'
import { join, dirname, basename, extname } from 'node:path'
import { execSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))   // websites/
const apps = join(root, '..')                                    // newapps1/
const cfg = JSON.parse(readFileSync(join(root, 'site.config.json'), 'utf8'))
const { domain, studio, contactEmail } = cfg
const year = String(new Date().getFullYear())
const out = join(root, 'deploy')
if (domain.includes('YOURDOMAIN')) console.warn('⚠️  site.config.json still has the placeholder domain.')

// Release version: date + short hash of everything built. Previous releases stay in
// deploy/releases/ so any version can be re-uploaded (rollback).
const stamp = new Date().toISOString().replace(/[-:]/g, '').replace(/\..*/, '').replace('T', '-')
for (const name of existsSync(out) ? readdirSync(out) : []) {
  if (name !== 'releases') rmSync(join(out, name), { recursive: true, force: true })
}
mkdirSync(join(out, 'zips'), { recursive: true })

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
const appURL = (a) => `https://${domain}/${a.id}/`

function walk(dir, fn) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    statSync(p).isDirectory() ? walk(p, fn) : fn(p)
  }
}

function excluded(rel, patterns) {
  const name = basename(rel)
  return patterns.some((p) => p.startsWith('*.') ? name.endsWith(p.slice(1))
    : rel === p || rel.startsWith(p + '/') || name === p)
}

const SECURE_EXCLUDES = [
  '.git', '.DS_Store', '*.md', '*.sh', '*.swift', '*.ts', '*.tsx', '*.map',
  '*.xcodeproj', '*.xcworkspace', 'node_modules', '*.yml', '*.yaml',
  '*.env', '*.log', '*.lock', 'Package.resolved', 'Package.swift', 'LICENSE',
  '.gitignore', '.oxlintrc.json', 'tsconfig.json'
]

function copyTree(src, dest, patterns = []) {
  mkdirSync(dest, { recursive: true })
  const combined = [...SECURE_EXCLUDES, ...patterns]
  cpSync(src, dest, {
    recursive: true,
    filter: (p) => { const rel = p.slice(src.length + 1); return rel === '' || !excluded(rel, combined) },
  })
}

function textReplace(dir, replacements) {
  walk(dir, (p) => {
    if (!['.html', '.js', '.css', '.xml', '.txt', '.json', '.webmanifest'].includes(extname(p))) return
    let s = readFileSync(p, 'utf8'), before = s
    for (const [from, to] of replacements) s = s.split(from).join(to)
    if (s !== before) writeFileSync(p, s)
  })
}

