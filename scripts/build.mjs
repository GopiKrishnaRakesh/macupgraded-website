const hashOf = (file) => createHash('sha256').update(readFileSync(file)).digest('hex').slice(0, 8)

function versionAssets(dir) {
  const attr = /(\b(?:href|src|content)=")(?!https?:|\/\/|data:|mailto:|#)([^"?#]+\.(?:css|js|png|jpe?g|webp|svg|ico|woff2?|webmanifest))(")/g
  walk(dir, (page) => {
    if (extname(page) !== '.html') return
    const html = readFileSync(page, 'utf8')
    const updated = html.replace(attr, (whole, pre, url, post) => {
      const target = url.startsWith('/') ? join(dir, url) : join(dirname(page), url)
      return existsSync(target) ? `${pre}${url}?v=${hashOf(target)}${post}` : whole
    })
    if (updated !== html) writeFileSync(page, updated)
  })
}

function stampVersion(dir, site, version) {
  walk(dir, (page) => {
    if (extname(page) !== '.html') return
    const html = readFileSync(page, 'utf8')
    if (html.includes('name="site-version"')) return
    writeFileSync(page, html.replace(/<head>/i, `<head>\n  <meta name="site-version" content="${version}">`))
  })
  writeFileSync(join(dir, 'version.json'), JSON.stringify({ site, version, built: new Date().toISOString() }, null, 2) + '\n')
}

function sitemapAndRobots(dir, base) {
  const pages = []
  walk(dir, (p) => { if (extname(p) === '.html') pages.push(p.slice(dir.length + 1)) })
  const urls = pages.sort().map((p) => `  <url><loc>${base}${p === 'index.html' ? '' : p}</loc></url>`).join('\n')
  writeFileSync(join(dir, 'sitemap.xml'),
    `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`)
  writeFileSync(join(dir, 'robots.txt'), `User-agent: *\nAllow: /\nSitemap: ${base}sitemap.xml\n`)
}

const common = [['{{DOMAIN}}', domain], ['{{STUDIO}}', studio], ['{{EMAIL}}', contactEmail], ['{{YEAR}}', year],
                ['privacy@YOUR-DOMAIN', contactEmail]]

// 1. Studio Master Portfolio site
const main = join(out, 'main')
copyTree(join(root, 'master'), main)
textReplace(main, common)
writeFileSync(join(main, '.htaccess'), htaccess())

// 2. Build each app and place it directly inside main/<app>/ (No subdomains!)
for (const a of cfg.apps) {
  const src = join(apps, a.source)
  if (!existsSync(join(src, 'index.html'))) throw new Error(`${a.name}: no index.html in ${src}`)
  
  // Destination inside main site
  const destInMain = join(main, a.id)
  copyTree(src, destInMain, a.exclude ?? [])
  for (const extra of a.extra ?? []) cpSync(join(apps, extra), join(destInMain, basename(extra)))
  const reps = [
    ...common,
    ['href="../"', 'href="../index.html"'],
    ["href='../'", "href='../index.html'"],
    ['href="../#', 'href="../index.html#'],
    ...cfg.apps.map((x) => [`href="../${x.id}/"`, `href="../${x.id}/index.html"`]),
    ...cfg.apps.map((x) => [`href="${x.id}/"`, `href="${x.id}/index.html"`]),
    ...(a.oldDomains ?? []).map((d) => [d, `${domain}/${a.id}`])
  ]
  textReplace(destInMain, reps)
  injectStrip(destInMain)
  
  // Also mirror to deploy/<id> standalone folder for convenience
  const destStandalone = join(out, a.id)
  copyTree(destInMain, destStandalone)
}

sitemapAndRobots(main, `https://${domain}/`)

// 3. Version every site, then zip it for Hostinger
const sites = ['main', ...cfg.apps.map((a) => a.id)]
const digest = createHash('sha256')
for (const site of sites) walk(join(out, site), (f) => digest.update(f.slice(out.length)).update(readFileSync(f)))
const contentHash = digest.digest('hex').slice(0, 7)

const latestFile = join(out, 'releases', 'LATEST')
const latest = existsSync(latestFile) ? readFileSync(latestFile, 'utf8').trim() : ''
const unchanged = latest.endsWith(`-${contentHash}`) && existsSync(join(out, 'releases', latest))
const version = unchanged ? latest : `${stamp}-${contentHash}`
const release = join(out, 'releases', version)
mkdirSync(release, { recursive: true })
if (unchanged) console.log(`No changes since ${version}; reusing that release.`)

for (const site of sites) {
  versionAssets(join(out, site))
  stampVersion(join(out, site), site, version)
  const zip = join(out, 'zips', `${site}.zip`)
  execSync(`cd "${join(out, site)}" && zip -qr "${zip}" . -x '.DS_Store'`)
  cpSync(zip, join(release, `${site}.zip`))
}
writeFileSync(join(out, 'releases', 'LATEST'), version + '\n')

// Report
const size = (p) => execSync(`du -sh "${p}"`).toString().split('\t')[0]
console.log(`Built for ${domain} (Single Domain, No Subdomains):`)
console.log(`  main (All Pages) → https://${domain}/  (${size(main)})`)
for (const a of cfg.apps) console.log(`  ${a.id.padEnd(16)} → ${appURL(a)}  (${size(join(main, a.id))})`)
console.log(`Version ${version}`)
console.log(`Main zip (Upload to public_html): ${join(out, 'zips', 'main.zip')}`)
